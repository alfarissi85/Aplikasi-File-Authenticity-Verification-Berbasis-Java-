    private void VerifyFileVerificationPageBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_VerifyFileVerificationPageBtnActionPerformed

        try {
            String PlainInput = FAVUIController.readFile(FileLocationPointerUnverifiedFileVerificationPageTextField.getText());
            String SignatureInput = FAVUIController.readFile(FileLocationPointerSignatureVerificationPageTextField.getText());
            long startTime = FAVUIController.beginProcessingTime();
            String MDPlain = FAVUIController.MD5HashFunction(PlainInput);
            String result = FAVUIController.decrypt(SignatureInput);
            boolean verificationResult = FAVUIController.verify(MDPlain, result);            
            double countPT = FAVUIController.endProcessingTime(startTime)/1000000;
            ProcessingTimeVerificationPage.setText(countPT + " ms");
            ShowMDfromUnverifiedFileVerificationPageTextArea.setText(MDPlain);
            ShowMDfromSignatureVerificationPageTextArea.setText(result);
            if(verificationResult == true){
                NotificationVerificationPagePanel.setVisible(true);
                VerificationFailedNotificationPanel.setVisible(false);
                VerificationSuccessPanel.setVisible(true);
                InvalidFileNotificationPanel.setVisible(false);
                BlankNotificationVerificationPagePanel.setVisible(false);

            }
            else{
                NotificationVerificationPagePanel.setVisible(true);
                VerificationSuccessPanel.setVisible(false);
                VerificationFailedNotificationPanel.setVisible(true);
                InvalidFileNotificationPanel.setVisible(false);
                BlankNotificationVerificationPagePanel.setVisible(false);

            }
        } catch (Exception ex) {
            NotificationVerificationPagePanel.setVisible(true);
            VerificationSuccessPanel.setVisible(false);
            VerificationFailedNotificationPanel.setVisible(false);
            InvalidFileNotificationPanel.setVisible(true);
            BlankNotificationVerificationPagePanel.setVisible(false);
        }
        BrowseFileUnverifiedVerificationPageBtn.setEnabled(false);
        BrowseFileSignatureVerificationPageBtn.setEnabled(false);
        VerifyFileVerificationPageBtn.setEnabled(false);
        ClearMDverificationPageBtn.setEnabled(true);
    }//GEN-LAST:event_VerifyFileVerificationPageBtnActionPerformed

