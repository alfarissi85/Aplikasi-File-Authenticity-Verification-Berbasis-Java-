    private void CountPTPageBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CountPTPageBtnActionPerformed
        String path = FileLocationPointerPlainTextPTPageTextField.getText();
        try {
            int bitsize = 1024;
            String input = FAVUIController.readFile(path);
            double PTEHB[] = new double [2], PTE[] = new double[2], PTVHB[] = new double[2], PTV[] = new double [2];
            for(int i = 0; i<2; i++){

                long startTime = 0;
                double countPT = 0;
                startTime = FAVUIController.beginProcessingTime();
                String result = FAVUIController.generateSignature(input, bitsize);
                countPT = FAVUIController.endProcessingTime(startTime)/1000000;
                PTEHB[i] = countPT;

                startTime = FAVUIController.beginProcessingTime();
                String EncryptWithoutHybrid = FAVUIController.MD5HashFunction(input);
                countPT = FAVUIController.endProcessingTime(startTime)/1000000;
                PTE[i] = countPT;

                String MDPlain1 = "";
                startTime = FAVUIController.beginProcessingTime();
                MDPlain1 = FAVUIController.MD5HashFunction(input);
                String MDsignature = FAVUIController.decrypt(result);
                Boolean VerificationWithHybrid = FAVUIController.verify(MDsignature, MDPlain1);
                countPT = FAVUIController.endProcessingTime(startTime)/1000000;
                PTVHB[i] = countPT;

                startTime = FAVUIController.beginProcessingTime();
                String MDPlain2 = FAVUIController.MD5HashFunction(input);
                Boolean VerificationWithoutHybrid = FAVUIController.verify(MDPlain1, MDPlain2);
                countPT = FAVUIController.endProcessingTime(startTime)/1000000;
                PTV[i] = countPT;

                bitsize = bitsize * 2;
            }
            EncryptionWithPTTextField.setText(PTEHB[0]+ " ms (1024 bit), " + PTEHB[1] + " ms (2048 bit)");
            if(PTE[0] < PTE[1])
            EncryptionWIthoutPTTextField.setText(PTE[1]+ " ms");
            else
            EncryptionWIthoutPTTextField.setText(PTE[0]+ " ms");

            VerificationWithPTTextField.setText(PTVHB[0]+ " ms (1024 bit), " + PTVHB[1] + " ms (2048 bit)");
            if(PTV[0] < PTV[1])
            VerificationWithoutPTTextField.setText(PTV[1]+ " ms");
            else
            VerificationWithoutPTTextField.setText(PTV[0]+ " ms");
        } catch (IOException ex) {
            Logger.getLogger(UIforFAV.class.getName()).log(Level.SEVERE, null, ex);
        }
        BrowsePTPageBtn.setEnabled(false);
        CountPTPageBtn.setEnabled(false);
        ClearPTPageBtn.setEnabled(true);
    }//GEN-LAST:event_CountPTPageBtnActionPerformed

